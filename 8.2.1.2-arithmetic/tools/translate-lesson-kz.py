def replace(s, pairs):
    for ru, kz in pairs:
        c = s.count(ru)
        if c != 1:
            sys.exit(f'Үзінді {c} рет табылды (күтілгені 1): {ru[:90]}')
        s = s.replace(ru, kz)
    return s


def main():
    s = SRC.read_text(encoding='utf-8')
    s = replace(s, HEAD)
    start, end = s.index('<div class="wrap">'), s.index('<script>')
    s = s[:start] + BODY.read_text(encoding='utf-8') + s[end:]
    s = replace(s, JS)
    DST.parent.mkdir(exist_ok=True)
    DST.write_text(s, encoding='utf-8')
    print(DST.relative_to(ROOT), 'дайын')


if __name__ == '__main__':
    main()
