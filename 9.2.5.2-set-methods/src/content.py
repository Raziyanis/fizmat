"""Содержание урока 9.2.5.2 «Жиын / Множество (set)» на двух языках.

T(ru, kk) — переводимая строка. Из одного описания собираются
L (русский урок) и LKK (казахская накладка, та же форма)."""


class T:
    def __init__(self, ru, kk):
        self.ru, self.kk = ru, kk


def pick(o, lang):
    """lang='ru' — полный урок; lang='kk' — только переведённое (накладка)."""
    if isinstance(o, T):
        return o.ru if lang == 'ru' else o.kk
    if isinstance(o, dict):
        out = {}
        for k, v in o.items():
            r = pick(v, lang)
            if lang == 'kk' and r is None:
                continue
            out[k] = r
        return out if (out or lang == 'ru') else None
    if isinstance(o, list):
        r = [pick(x, lang) for x in o]
        if lang == 'kk' and all(x is None for x in r):
            return None
        return r
    return o if lang == 'ru' else None


