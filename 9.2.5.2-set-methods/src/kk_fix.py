def apply(objs, T):
    used = set()

    def walk(o):
        if isinstance(o, T):
            if o.kk in FIX:
                used.add(o.kk)
                o.kk = FIX[o.kk]
        elif isinstance(o, dict):
            for v in o.values():
                walk(v)
        elif isinstance(o, (list, tuple)):
            for v in o:
                walk(v)

    seen = set()
    for x in objs:
        stack = [x]
        # один и тот же T может встречаться несколько раз — меняем один раз
        def walk_once(o):
            if isinstance(o, T):
                if id(o) in seen:
                    return
                seen.add(id(o))
                walk(o)
            elif isinstance(o, dict):
                for v in o.values():
                    walk_once(v)
            elif isinstance(o, (list, tuple)):
                for v in o:
                    walk_once(v)
        walk_once(x)
    missing = [k for k in FIX if k not in used and FIX[k] != k]
    return missing
