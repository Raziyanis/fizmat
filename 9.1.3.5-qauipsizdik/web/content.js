  function empty(t) {
    switch (t.type) {
      case 'match': return t.left.map(function () { return null; });
      case 'fill': return t.blanks.map(function () { return null; });
      case 'tf': return t.items.map(function () { return null; });
      case 'hot': return t.parts.map(function () { return false; });
      case 'sort': return t.items.map(function () { return null; });
      case 'order': return t.start.slice();
      case 'chat': return t.steps.map(function () { return null; });
      case 'multi': return t.opts.map(function () { return false; });
      case 'text': return '';
    }
  }
  // Әр тармақ дұрыс па (талдау үшін); hot/multi үшін: белгіленгені дұрыс па
  function score(t, a) {
    var n = 0, i;
    switch (t.type) {
      case 'match': for (i = 0; i < t.key.length; i++) if (a[i] === t.key[i]) n++; return n;
      case 'fill': for (i = 0; i < t.blanks.length; i++) if (a[i] === t.blanks[i].key) n++; return n;
      case 'tf': for (i = 0; i < t.items.length; i++) if (a[i] === t.items[i].v) n++; return n;
      case 'sort': for (i = 0; i < t.items.length; i++) if (a[i] === t.items[i].bin) n++; return n;
      case 'order': for (i = 0; i < a.length; i++) if (a[i] === i) n++; return n;     // a[k] — k-орындағы элемент; дұрыс рет: 0, 1, 2, 3
      case 'chat': for (i = 0; i < t.steps.length; i++) if (a[i] === t.steps[i].key) n++; return n;
      case 'hot': case 'multi': {
        var list = t.type === 'hot' ? t.parts : t.opts, good = 0, wrong = 0;
        for (i = 0; i < list.length; i++) if (a[i]) { if (t.type === 'hot' ? list[i].bad : list[i].ok) good++; else wrong++; }
        return Math.max(0, good - wrong);                                        // артық белгі балды азайтады
      }
    }
  }
  function touched(t, a) {
    if (t.type === 'text') return String(a || '').trim().length > 0;
    if (t.type === 'order') return a.some(function (v, i) { return v !== t.start[i]; });
    if (t.type === 'hot' || t.type === 'multi') return a.some(Boolean);
    return a.some(function (v) { return v !== null; });
  }
  function complete(t, a) {
    if (t.type === 'text') return words(a).length >= t.minWords;
    if (t.type === 'order' || t.type === 'hot' || t.type === 'multi') return touched(t, a);
    return a.every(function (v) { return v !== null; });
  }
