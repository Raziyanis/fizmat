def main():
    s = SRC.read_text(encoding='utf-8')
    for item in PAIRS:
        ru, kz = item[0], item[1]
        n = item[2] if len(item) > 2 else 1
        c = s.count(ru)
        if c != n:
            sys.exit(f'Үзінді {c} рет табылды (күтілгені {n}): {ru[:80]}')
        s = s.replace(ru, kz)
    DST.write_text(s, encoding='utf-8')
    print(DST.name, 'дайын')


if __name__ == '__main__':
    main()
